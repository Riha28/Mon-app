const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("dlc_lang") || "fr");
  useEffect(() => {
    localStorage.setItem("dlc_lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const t = (key, params) => {
    let s = (DICT[lang] && DICT[lang][key]) || (DICT.fr[key]) || key;
    if (params) for (const k in params) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), params[k]);
    return s;
  };
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
